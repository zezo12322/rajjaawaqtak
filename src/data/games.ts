export type DayEnding = { title: string; color: string; text: string }

/** أقصى مجموع ممكن = ٦ مشاهد × (وقت+تركيز+راحة) */
export function dayEnding(total: number): DayEnding {
  if (total >= 30)
    return {
      title: "يوم رجّعته بالكامل 🌿",
      color: "#16a34a",
      text: "قراراتك النهاردة كسبتك ساعات وتركيز وراحة. كده إنت مش بتقاوم الموبايل — إنت بتستخدمه لما إنت عايز. شارك طريقتك مع غيرك في حائط النصايح.",
    }
  if (total >= 14)
    return {
      title: "يوم متوازن 👏",
      color: "#c2790a",
      text: "أغلب اختياراتك كانت في صالحك، وفيه لحظتين الموبايل كسبك فيهم. حدّد اللحظة الأصعب عندك وابدأ منها في تحدي الـ٧ أيام.",
    }
  if (total >= 0)
    return {
      title: "يوم على الحافة ⚠️",
      color: "#d97706",
      text: "اليوم عدّى، بس جزء كبير منه راح في التمرير. مش محتاج تغيّر كل حاجة — غيّر قرار واحد بس: مكان الشاحن بالليل.",
    }
  return {
    title: "يوم الموبايل كسب فيه 🚨",
    color: "#dc2626",
    text: "الشاشة أخدت الصبح والضهر والليل. الخبر الحلو إن كل مشهد فات كان فيه اختيار تاني — جرّب اللعبة تاني واختار غيره وشوف الفرق.",
  }
}
